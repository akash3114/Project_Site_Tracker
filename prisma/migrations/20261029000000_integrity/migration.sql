-- Phase 1: integrity, timezone and index normalisation.
--
-- 1. Normalise email case and add a functional unique index, so the database
--    agrees with the API (which lowercases every email).
-- 2. De-duplicate the "primary" flags before enforcing them:
--      * one primary project manager per project
--      * one primary holder per plaza + role
--    The oldest assignment (assignedAt, then userId) wins.
-- 3. Add the missing query indexes and move timestamps to timestamptz(3).
-- 4. Make every user reference RESTRICT: users are deactivated, never deleted,
--    so a delete must never silently null out history.
-- 5. Drop the pilot backup table that the docs said a later migration would
--    remove.

-- 1. Email case -------------------------------------------------------------
UPDATE "User"
SET "email" = lower("email")
WHERE "email" <> lower("email");

CREATE UNIQUE INDEX "User_email_lower_key" ON "User" (lower("email"));

-- 2. Primary flags ----------------------------------------------------------
WITH ranked AS (
    SELECT ctid,
           row_number() OVER (
               PARTITION BY "projectId"
               ORDER BY "assignedAt" ASC, "userId" ASC
           ) AS rn
    FROM "ProjectAssignment"
    WHERE "isPrimary"
)
UPDATE "ProjectAssignment" AS pa
SET "isPrimary" = false
FROM ranked AS r
WHERE pa.ctid = r.ctid
  AND r.rn > 1;

WITH ranked AS (
    SELECT ctid,
           row_number() OVER (
               PARTITION BY "plazaId", "role"
               ORDER BY "assignedAt" ASC, "userId" ASC
           ) AS rn
    FROM "PlazaAssignment"
    WHERE "isPrimary"
)
UPDATE "PlazaAssignment" AS pa
SET "isPrimary" = false
FROM ranked AS r
WHERE pa.ctid = r.ctid
  AND r.rn > 1;

CREATE UNIQUE INDEX "ProjectAssignment_projectId_primary_key"
    ON "ProjectAssignment" ("projectId")
    WHERE "isPrimary";

CREATE UNIQUE INDEX "PlazaAssignment_plazaId_role_primary_key"
    ON "PlazaAssignment" ("plazaId", "role")
    WHERE "isPrimary";

