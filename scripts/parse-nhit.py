"""Parse 'NHIT Project List.xlsx' (sheet 'NHIT Assets') into prisma/nhit-data.ts.

Rules (agreed):
- New project group starts at a row with S.No set; blank S.No rows continue it.
- AS row (no S.No, acronym AS, Undvariya) folds into Palanpur - Aburoad- Swaroopganj.
- Amravati - Chikhali rows (S.No 5,6,7) merge into ONE project, 3 plazas.
- Anandapuram x2 stay separate (distinct names).
- People: split <br>/newlines into individuals; strip phones + parenthetical
  annotations; drop NA/blank. Same cleaned name = same person (seed dedupes).
- Length: numeric, or '=a+b+...' formula evaluated; blank -> None.
"""
import json
import openpyxl
import os
import re

# Canonical source is docs/NHIT Project List.xlsx. Override when it is locked
# (e.g. open in Excel / OneDrive sync): NHIT_XLSX=/tmp/nhit-src.xlsx python ...
SRC = os.environ.get("NHIT_XLSX", "docs/NHIT Project List.xlsx")
DST = "prisma/nhit-data.ts"

PHONE = re.compile(r"\(?\+?\d[\d\s]{9,}\d\)?")
PAREN = re.compile(r"\s*\([^)]*\)")
WS = re.compile(r"\s+")


def clean_name(raw):
    if raw is None:
        return []
    parts = re.split(r"<br>|\n", str(raw))
    out = []
    for p in parts:
        p = PHONE.sub("", p)
        p = PAREN.sub("", p)
        p = WS.sub(" ", p).strip(" -,")
        if not p or p.upper() == "NA":
            continue
        out.append(p)
    return out


def clean_text(v):
    if v is None:
        return None
    s = WS.sub(" ", str(v).replace("\ufffd", "-")).strip(" -,")
    return s or None


def length_of(v):
    if v is None:
        return None
    if isinstance(v, (int, float)):
        return round(float(v), 3)
    s = str(v).strip()
    if s.startswith("="):
        try:
            return round(sum(float(x) for x in s[1:].split("+")), 3)
        except ValueError:
            return None
    try:
        return round(float(s), 3)
    except ValueError:
        return None


wb = openpyxl.load_workbook(SRC, read_only=True, data_only=True)
ws = wb["NHIT Assets"]
rows = list(ws.iter_rows(values_only=True))

# Col layout: 0 S.No, 1 Project, 2 Acronym, 3 State, 4 plaza count, 5 plaza,
# 6 length, 7 PM, 8 PIU, 9 RO, 10 toll, 11 maintenance, 12 corridor.
projects = []
current = None
current_round = None
for r in rows:
    c0 = clean_text(r[0])
    if c0 and c0.startswith("Round"):
        current_round = c0
        continue
    if r[1] is None and r[5] is None:
        continue
    if c0 and c0.isdigit():
        current = {
            "sno": c0,
            "round": current_round,
            "name": clean_text(r[1]),
            "acronym": clean_text(r[2]),
            "state": clean_text(r[3]),
            "plazas": [],
            "pms": clean_name(r[7]),
        }
        projects.append(current)
    if current is None:
        continue
    plaza_name = clean_text(r[5])
    if plaza_name:
        current["plazas"].append({
            "name": plaza_name,
            "lengthKm": length_of(r[6]),
            "state": clean_text(r[3]),
            "piu": clean_text(r[8]),
            "ro": clean_text(r[9]),
            "toll": clean_name(r[10]),
            "maintenance": clean_name(r[11]),
            "corridor": clean_name(r[12]),
        })

# Override 1: AS row (Undvariya) folds into Palanpur - Aburoad- Swaroopganj.
# It parsed as its own group only if it had S.No; it has none, so it already
# attached to the Palanpur group. Verify:
pal = [p for p in projects if p["name"] and "Palanpur" in p["name"]]
assert len(pal) == 1, f"Palanpur groups: {pal}"
assert any(z["name"] == "Undvariya" for z in pal[0]["plazas"]), "Undvariya missing!"

# Override 2: merge the three 'Amravati - Chikhali' groups into one.
am = [p for p in projects if p["name"] == "Amravati - Chikhali"]
assert len(am) == 3, f"Amravati groups: {len(am)}"
merged = {
    "sno": am[0]["sno"],
    "round": am[0]["round"],
    "name": "Amravati - Chikhali",
    "acronym": am[0]["acronym"],
    "state": am[0]["state"],
    "plazas": [z for p in am for z in p["plazas"]],
    "pms": [pm for p in am for pm in p["pms"]],
}
projects = [p for p in projects if p["name"] != "Amravati - Chikhali"]
projects.append(merged)

# Drop helper keys, sort by round then name for stable seed order.
for p in projects:
    p.pop("sno", None)
projects.sort(key=lambda p: (p["round"] or "", p["name"] or ""))

n_plazas = sum(len(p["plazas"]) for p in projects)
people = set()
for p in projects:
    people.update(p["pms"])
    for z in p["plazas"]:
        people.update(z["toll"] + z["maintenance"] + z["corridor"])
print(f"projects={len(projects)} plazas={n_plazas} people={len(people)}")

out = (
    "// Generated by scripts/parse-nhit.py from 'NHIT Project List.xlsx'.\n"
    "// Do not edit by hand — fix the parser and re-run.\n"
    "export interface NhitPlaza {\n"
    "  name: string;\n"
    "  lengthKm: number | null;\n"
    "  state: string | null;\n"
    "  piu: string | null;\n"
    "  ro: string | null;\n"
    "  toll: string[];\n"
    "  maintenance: string[];\n"
    "  corridor: string[];\n"
    "}\n"
    "export interface NhitProject {\n"
    "  name: string;\n"
    "  acronym: string | null;\n"
    "  state: string | null;\n"
    "  round: string | null;\n"
    "  pms: string[];\n"
    "  plazas: NhitPlaza[];\n"
    "}\n"
    "export const NHIT_PROJECTS: NhitProject[] = "
    + json.dumps(projects, indent=2, ensure_ascii=False)
    + ";\n"
)
with open(DST, "w", encoding="utf-8") as f:
    f.write(out)
print(f"wrote {DST}")
